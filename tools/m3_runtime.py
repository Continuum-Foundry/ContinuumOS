"""P3-01 contract/profile validation and bounded HOST lifecycle fixture.

No guest code is executed here. Actual baseline VMs use Test-P1-07.ps1.
Only this script's fixed child can be launched; no arbitrary executable option.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys
import time

ROOT = Path(__file__).resolve().parents[1]
PROFILE = ROOT / "config/m3-profiles.json"
CONTRACT = ROOT / "contracts/runtime-v0.json"
PROFILE_PROTOCOL_SHA256 = "d0589f1cbe8c4e9ee062b88f79258328df2a242abf236fbde027c4c4a94145de"


def digest(path):
    h = hashlib.sha256()
    with Path(path).open("rb") as stream:
        for block in iter(lambda: stream.read(65536), b""):
            h.update(block)
    return h.hexdigest()


def require(condition, message):
    if not condition:
        raise ValueError(message)


def no_duplicates(pairs):
    result = {}
    for key, value in pairs:
        require(key not in result, "duplicate JSON key: " + key)
        result[key] = value
    return result


def read_json(path):
    with Path(path).open("rb") as stream:
        data = stream.read(65537)
    require(len(data) <= 65536, "JSON input exceeds 64 KiB")
    try:
        return json.loads(data, object_pairs_hook=no_duplicates)
    except RecursionError as error:
        raise ValueError("JSON nesting exceeds decoder bound") from error


def save(path, value):
    Path(path).write_text(json.dumps(value, indent=2) + "\n", encoding="utf-8")


def validate_profile(profile):
    # Version 1 is an exact measurement protocol, including nested types/keys.
    # A changed capacity needs a reviewed new profile revision, never an override.
    canonical = json.dumps(profile, sort_keys=True, separators=(",", ":")).encode()
    require(hashlib.sha256(canonical).hexdigest() == PROFILE_PROTOCOL_SHA256,
            "unsupported CPU/profile/limits/measurement protocol")


def validate_contract(c):
    require(set(c) == set(read_json(CONTRACT)), "unknown/missing contract field")
    require(c["revision"] == 0 and c["status"] == "experimental-unfrozen", "ABI freeze prohibited")
    require(c["syscall"]["numbers_frozen"] is False, "ABI numbers not frozen")
    require(sum(n for _, n in c["startup_fields"]) == c["entry"]["context_bytes"] == 64,
            "startup encoding size mismatch")
    require(sum(n for _, n in c["message_fields"]) == 48, "message header size mismatch")
    for key in ("startup_fields", "message_fields"):
        names = [name for name, _ in c[key]]
        require(len(set(names)) == len(names), "duplicate encoded field")
        require(all(type(n) is int and n in (2, 4, 8, 16) for _, n in c[key]), "bad field width")
    for key in ("operations", "errors"):
        require(len(c[key]) == len(set(c[key])), "duplicate SDK name")
    require(c == read_json(CONTRACT), "unsupported contract revision")


def generate(destination):
    c = read_json(CONTRACT)
    validate_contract(c)
    lines = ["#![no_std]",
             "// Generated by tools/m3_runtime.py; draft names/offsets only, NO ABI IDs.",
             f'// contract SHA-256: {digest(CONTRACT)}',
             "pub const DRAFT_REVISION: u32 = 0;"]
    for key, prefix in (("startup_fields", "STARTUP"), ("message_fields", "MESSAGE")):
        offset = 0
        for name, width in c[key]:
            lines.append(f"pub const {prefix}_{name.upper()}_OFFSET: usize = {offset};")
            offset += width
        lines.append(f"pub const {prefix}_BYTES: usize = {offset};")
    lines += ["pub enum DraftOperation { " + ", ".join(
        "".join(part.title() for part in name.split("_")) for name in c["operations"]) + " }",
        "pub enum DraftError { " + ", ".join(c["errors"]) + " }"]
    # Enum discriminants are compiler-local; never repr(), serialized or syscall IDs.
    Path(destination).write_text("\n".join(lines) + "\n", encoding="utf-8")


def image_check(path, expected, maximum):
    path = Path(path).resolve(strict=True)
    require(path.is_file() and 64 <= path.stat().st_size <= maximum, "image size outside bounds")
    require(digest(path) == expected, "image digest mismatch")
    with path.open("rb") as stream:
        header = stream.read(24)
    require(header[:7] == b"\x7fELF\x02\x01\x01" and
            header[16:20] == b"\x02\x00\x3e\x00", "not a static x86-64 ELF64 LE image")
    # This is identity/header admission only. The P3-03 loader owns segment validation.
    return path


def child(case, run_id, image_sha256):
    if case == "timeout":
        time.sleep(60)
    elif case == "nonzero":
        return 7
    elif case == "missing-final":
        print(json.dumps({"version": 1, "event": "started", "run_id": run_id}))
    else:
        print(json.dumps({"version": 1, "event": "complete", "run_id": run_id,
                          "image_sha256": image_sha256}))
    return 0


def run(profile_path, image, image_sha256, case, interpreter=None):
    directory = ROOT / "build/m3/P3-01" / f"run-{time.time_ns()}-{os.getpid()}"
    directory.mkdir(parents=True)
    report = {"schema_version": 1, "scope": "host-lifecycle-only; image never executed",
              "case": case, "launched": False, "cleanup": "not-launched", "exit_code": None,
              "outcome": "validation-rejected", "parent_pid": os.getpid(),
              "run_id": directory.name, "runner_sha256": digest(__file__),
              "python": sys.version, "host_platform": sys.platform}
    proc = None
    try:
        p = read_json(profile_path)
        validate_profile(p)
        validate_contract(read_json(CONTRACT))
        require(case in ("success", "nonzero", "missing-final", "timeout"), "unknown fixture")
        report.update(profile_sha256=digest(profile_path), contract_sha256=digest(CONTRACT))
        image_path = image_check(image, image_sha256, p["runner"]["image_bytes"])
        report.update(image_sha256=digest(image_path), image_bytes=image_path.stat().st_size)
        exe = Path(interpreter or sys.executable).resolve(strict=True)
        # An explicit unavailable tool is testable; an alternate executable is never run.
        require(exe == Path(sys.executable).resolve(), "only the current Python interpreter is allowed")
        report["interpreter_sha256"] = digest(exe)
        args = [str(exe), str(Path(__file__).resolve()), "child", case,
                directory.name, image_sha256]
        report["arguments"] = [a.replace(str(ROOT), "${WORKSPACE}") for a in args]
        deadline = p["runner"]["timeout_case_ms" if case == "timeout" else "fixture_timeout_ms"]
        report["deadline_ms"] = deadline
        start = time.perf_counter_ns()
        with (directory / "stdout.log").open("xb") as out, (directory / "stderr.log").open("xb") as err:
            report["outcome"] = "spawn-failed"
            proc = subprocess.Popen(args, stdin=subprocess.DEVNULL, stdout=out, stderr=err,
                                    creationflags=subprocess.CREATE_NO_WINDOW if os.name == "nt" else 0)
            report.update(launched=True, cleanup="unconfirmed", child_pid=proc.pid)
            report["outcome"] = "running"
            while proc.poll() is None:
                if any((directory / n).stat().st_size > p["runner"]["output_bytes"]
                       for n in ("stdout.log", "stderr.log")):
                    report["outcome"] = "output-limit"
                    proc.kill()
                    break
                if time.perf_counter_ns() - start >= deadline * 1_000_000:
                    report["outcome"] = "timeout"
                    proc.kill()
                    break
                time.sleep(p["runner"]["poll_ms"] / 1000)
            report["exit_code"] = proc.wait(timeout=5)
            report["cleanup"] = "reaped"
        report["elapsed_ns"] = time.perf_counter_ns() - start
        if any((directory / n).stat().st_size > p["runner"]["output_bytes"]
               for n in ("stdout.log", "stderr.log")):
            report["outcome"] = "output-limit"
        if report["outcome"] in ("timeout", "output-limit"):
            raise ValueError(report["outcome"])
        require(report["exit_code"] == 0, "exited-nonzero")
        observed = read_json(directory / "stdout.log")
        require(observed == {"version": 1, "event": "complete", "run_id": directory.name,
                             "image_sha256": image_sha256}, "missing-final-record")
        report["outcome"] = "complete"
    except (OSError, ValueError, subprocess.SubprocessError) as error:
        report["error"] = str(error).replace(str(ROOT), "${WORKSPACE}")
        if report["launched"] and report["outcome"] == "running":
            report["outcome"] = ("harness-failure" if report["exit_code"] is None else
                                 "exited-nonzero" if report["exit_code"] else "missing-final-record")
    finally:
        if proc is not None and report["cleanup"] != "reaped":
            try:
                if proc.poll() is None:
                    proc.kill()
                proc.wait(timeout=5)
                report["cleanup"] = "reaped"
            except (OSError, subprocess.SubprocessError):
                report["cleanup"] = "unconfirmed"
        save(directory / "result.json", report)
    return directory, report


def main():
    if len(sys.argv) == 5 and sys.argv[1] == "child":
        return child(*sys.argv[2:])
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    gen = sub.add_parser("generate")
    gen.add_argument("destination", type=Path)
    fixture = sub.add_parser("run")
    fixture.add_argument("--config", type=Path, default=PROFILE)
    fixture.add_argument("--image", type=Path, required=True)
    fixture.add_argument("--sha256", required=True)
    fixture.add_argument("--case", default="success")
    args = parser.parse_args()
    if args.command == "generate":
        generate(args.destination)
        return 0
    directory, report = run(args.config, args.image, args.sha256, args.case)
    print(directory)
    return 0 if report["outcome"] == "complete" else 1


if __name__ == "__main__":
    sys.exit(main())
